#!/usr/bin/env python3
import sys
import os
import hashlib

EXPECTED_SHA256 = "f3cfac8a662a45fd00fc9a310217cec3db61c397e843eb4a1637af94eb302c76"

def main():
    if len(sys.argv) < 3:
        print("Usage: embed_nnue.py <path/to/nnue.weights> <path/to/output.cpp>", file=sys.stderr)
        sys.exit(1)

    weights_path = os.path.abspath(sys.argv[1])
    output_cpp = os.path.abspath(sys.argv[2])

    if not os.path.isfile(weights_path):
        print(f"Error: NNUE weight file not found: {weights_path}", file=sys.stderr)
        sys.exit(1)

    with open(weights_path, "rb") as f:
        data = f.read()

    actual_sha256 = hashlib.sha256(data).hexdigest()
    if actual_sha256 != EXPECTED_SHA256:
        print(f"Error: NNUE weight SHA256 mismatch!\nExpected: {EXPECTED_SHA256}\nActual:   {actual_sha256}", file=sys.stderr)
        sys.exit(1)

    weights_incbin_path = weights_path.replace("\\", "/")

    os.makedirs(os.path.dirname(output_cpp), exist_ok=True)

    cpp_content = f"""// Auto-generated by scripts/embed_nnue.py - DO NOT EDIT
#include <cstddef>

#if defined(_WIN32)
__asm__(
    ".section .rdata,\\\"dr\\\"\\n"
    ".balign 64\\n"
    ".globl EmbeddedNNUEWeightsData\\n"
    "EmbeddedNNUEWeightsData:\\n"
    ".incbin \\"{weights_incbin_path}\\"\\n"
    ".globl EmbeddedNNUEWeightsEnd\\n"
    "EmbeddedNNUEWeightsEnd:\\n"
    ".text\\n"
);
#else
__asm__(
    ".section .rodata\\n"
    ".balign 64\\n"
    ".globl EmbeddedNNUEWeightsData\\n"
    "EmbeddedNNUEWeightsData:\\n"
    ".incbin \\"{weights_incbin_path}\\"\\n"
    ".globl EmbeddedNNUEWeightsEnd\\n"
    "EmbeddedNNUEWeightsEnd:\\n"
    ".text\\n"
);
#endif

extern "C" const unsigned char EmbeddedNNUEWeightsData[];
extern "C" const unsigned char EmbeddedNNUEWeightsEnd[];

extern "C" const unsigned char* GetEmbeddedNNUEData() {{
    return EmbeddedNNUEWeightsData;
}}

extern "C" std::size_t GetEmbeddedNNUESize() {{
    return static_cast<std::size_t>(EmbeddedNNUEWeightsEnd - EmbeddedNNUEWeightsData);
}}
"""

    with open(output_cpp, "w") as f:
        f.write(cpp_content)

    print(f"Embedded NNUE source generated: {output_cpp} ({len(data)} bytes, SHA256: {actual_sha256})")

if __name__ == "__main__":
    main()
